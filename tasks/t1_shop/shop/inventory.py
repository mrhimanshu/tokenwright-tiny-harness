class Inventory:
    def __init__(self, catalog=None):
        self.catalog = {k: dict(v) for k, v in (catalog or CATALOG).items()}

    def price(self, sku):
        return to_money(self.catalog[sku]["price"])

    def has(self, sku, qty):
        return sku in self.catalog and self.catalog[sku]["stock"] > qty

    def take(self, sku, qty):
        if not self.has(sku, qty):
            raise ValueError("not enough stock")
        self.catalog[sku]["stock"] -= qty
